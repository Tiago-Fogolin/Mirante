def _titulo(texto, limite=90):
    texto = texto.strip()
    if len(texto) <= limite:
        return texto
    corte = texto.rfind(" ", 0, limite)
    if corte == -1:
        corte = limite
    return texto[:corte].rstrip(",;.") + "…"


def _montar_observacoes(dados):
    partes = [f"Fonte: {dados['fonte']}"]
    if dados.get("tipo_fonte"):
        partes.append(f"Tipo de fonte: {dados['tipo_fonte']}")
    if dados.get("data_fonte"):
        partes.append(f"Data da fonte: {dados['data_fonte']}")
    if dados.get("confianca"):
        partes.append(f"Confiança: {dados['confianca']}")
    return " | ".join(partes)


def seed_atores_acoes():
    db = SessionLocal()
    try:
        municipio = db.query(Municipio).filter(Municipio.nome == MUNICIPIO_PADRAO).first()
        if not municipio:
            print(f"Município '{MUNICIPIO_PADRAO}' não encontrado, abortando.")
            return

        for dados in ACOES_ENCONTRADAS:
            descricao = dados["acao"]
            titulo = _titulo(descricao)

            existente = (
                db.query(Acao)
                .filter(Acao.nome_organizacao == dados["entidade"], Acao.descricao == descricao)
                .first()
            )
            if existente:
                print(f"Ação de '{dados['entidade']}' já existe, pulando.")
                continue

            tema = None
            if dados.get("area"):
                tema = db.query(Tema).filter(Tema.nome == dados["area"]).first()
                if not tema:
                    tema = Tema(nome=dados["area"], descricao=f"Ações relacionadas a {dados['area']}")
                    db.add(tema)
                    db.flush()

            site = dados.get("site")
            if site in ("Não localizado", "Nao localizado"):
                site = None

            nova_acao = Acao(
                nome_organizacao=dados["entidade"],
                documento_ator=dados.get("cnpj"),
                tipo_ator=dados.get("tipo_ator"),
                website=site,
                abrangencia_geografica=dados.get("abrangencia"),
                municipio_id=municipio.id,
                status=StatusAcaoEnum.EM_ANDAMENTO,
                titulo=titulo,
                descricao=descricao,
                observacoes=_montar_observacoes(dados),
            )
            if tema:
                nova_acao.temas = [tema]

            db.add(nova_acao)
            db.flush()

            for numero_ods in dados.get("ods", []):
                ods_obj = db.query(ODS).filter(ODS.numero == numero_ods).first()
                if not ods_obj:
                    print(f"ODS número {numero_ods} não encontrado, pulando vínculo.")
                    continue
                db.add(AcaoOds(acao_id=nova_acao.id, ods_id=ods_obj.id))

            print(f"Ação de '{dados['entidade']}' criada (ODS: {dados.get('ods') or 'nenhuma'}).")

        db.commit()
        print("Seed de ações (compilado atores x ações) concluído.")
    except Exception as e:
        print(f"❌ Erro ao semear ações do compilado: {e}")
        db.rollback()
    finally:
        db.close()


if __name__ == "__main__":
    seed_atores_acoes()
